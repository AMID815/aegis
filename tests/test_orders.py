@pytest.mark.parametrize("price, ceiled", [
    (199900, 199900),   # 이미 100원 단위 — 그대로 (밴드 안)
    (199999, 200000),   # 올림이 밴드 경계를 넘는다: 200,000원부터 500원 단위
    (49999, 50000),     # 50,000원부터 100원 단위
    (4999, 5000),       # 5,000원부터 10원 단위
    (19999, 20000),     # 20,000원부터 50원 단위
    (499999, 500000),   # 500,000원부터 1,000원 단위
])
def test_올림이_밴드_경계를_넘어도_주문_가능한_가격이다(price, ceiled):
    """ceil_tick 은 **원래 가격이 속한 밴드**의 호가단위로 올린다. 그
    결과가 다음 밴드로 넘어갈 수 있다(예: 199,999원을 100원 단위로 올리면
    200,000원인데, 200,000원부터는 500원 단위 밴드다). 넘어가도 문제
    없는 이유: 모든 밴드 경계값(2,000 / 5,000 / 20,000 / 50,000 /
    200,000 / 500,000)은 5의 배수라 그 위 밴드의 더 굵은 호가단위로도
    나누어떨어진다 — 그래서 올림 결과는 항상 주문 가능한 가격이다."""
    v = orders.ceil_tick(price)
    assert v == ceiled
    assert v % orders.tick_size(v) == 0


def test_사다리가_실제로_주문_가능한_가격이다():
    """이 기능의 전제 자체다 — '지정가를 걸었다면' 이 성립하려면 그 가격에
    주문이 존재할 수 있어야 한다. 232,650원짜리 주문은 없다."""
    for first in (1524, 13750, 32250, 115800, 247500, 2987000):
        p = orders.plan(first)
        for k in ("buy2", "buy3"):
            v = p[k]
            assert v % orders.tick_size(v) == 0, f"{first}원 → {k}={v} 는 호가에 안 맞음"


def test_익절선_손절선도_주문_가능한_가격이다():
    for first in (1524, 13750, 32250, 115800, 247500, 2987000):
        p = orders.plan(first)
        for filled in ([first], [first, p["buy2"]], [first, p["buy2"], p["buy3"]]):
            tp = orders.take_profit(filled)
            assert tp % orders.tick_size(tp) == 0, f"익절 {tp} 가 호가에 안 맞음"
            sl = orders.stop_loss(filled)
            if sl is not None:
                assert sl % orders.tick_size(sl) == 0, f"손절 {sl} 가 호가에 안 맞음"



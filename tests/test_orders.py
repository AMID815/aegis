def test_재생은_since_이하의_분봉을_건너뛴다():
    """설계 §4-1 이 한 호출 안에서 막은 소급 체결이, 호출 **사이**로 새는 걸
    막는다.

    close.yml 은 하루 두 번 돈다(cron "0 8,23"). 두 번째 실행은 개장 전이라
    같은 거래일을 다시 처리하는데, 그때 filled 에는 이미 그날 체결된 매수가
    들어 있다. since 없이 그날 전체를 다시 재생하면, 2차 체결(10:00)보다
    이른 09:30 분봉이 **내려간 익절선**(102,141)으로 평가되어 떨어지는
    종목이 +5.3% 승리로 기록된다 — 2026-08-20 실측 재현.
    """
    어제 = [
        bar("202608190900", 101000, 100000),
        bar("202608190930", 103000, 101000),   # 고가가 내려간 익절선을 넘는다
        bar("202608191000",  99000,  94000),   # 여기서 2차가 체결됐었다
        bar("202608191530",  95000,  94000),
    ]
    p = orders.plan(100000)
    # since 없이: 09:30 에 익절이 소급 체결된다 (고쳐야 할 동작)
    잘못 = orders.replay(p, [100000, 94000], 어제)
    assert 잘못 and 잘못[0]["kind"] == "take_profit"
    assert 잘못[0]["t"] == "202608190930"

    # since 를 마지막 체결 시각으로 주면 그 구간이 잘려 나간다
    맞음 = orders.replay(p, [100000, 94000], 어제, since="202608191000")
    assert 맞음 == []


def test_since_는_경계값을_포함해_자른다():
    """같은 분에 체결이 났으면 그 분은 이미 처리된 것이다 — 다시 보면 안 된다."""
    p = orders.plan(100000)
    bars = [bar("202608200930", 106000, 99000)]

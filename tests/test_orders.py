def test_반올림이지_절단이_아니다():
    """`int()` 로 바꾸면 실패해야 하는 테스트 — 이게 없으면 '계통적 편향
    방지'라고 적어둔 결정을 아무것도 지키지 않는다(2026-08-20 리뷰가
    mutation 으로 확인: round→int 로 바꿔도 8개 전부 통과했다).

    기존 테스트 입력이 전부 나누어떨어지는 값이라(247,500 × 0.94 = 232,650.0)
    반올림 자체가 발동하지 않았다. 여기서는 일부러 안 떨어지는 값을 쓴다.

    **호가단위 반영(2026-08-20) 이후 주의**: buy2/buy3/take_profit/stop_loss
    는 이제 round() 다음에 floor_tick·ceil_tick 을 한 번 더 거친다. tick 이
    10 이상인 구간에서는 round 와 int 가 만드는 1원 차이가 같은 tick
    버킷으로 묶여버려 결과가 같아질 수 있다 — 즉 이 mutation 을 더 이상
    잡지 못하는 입력이 생긴다. 그래서 여기서는 결과가 2,000원 미만이 되게
    입력을 고른다 — 그 구간의 호가단위는 1원이라 floor_tick·ceil_tick 이
    항등함수라서, round↔int 차이가 tick 단계에 가려지지 않고 그대로
    드러난다."""
    # 1401 × 0.88 = 1232.88 → 반올림 1233, 절단 1232 (구분됨). 결과 1233 은
    # 2,000원 미만이라 tick=1, floor_tick 이 항등함수라 반올림 차이가 그대로 남는다.
    assert orders.plan(1401)["buy3"] == 1233

    # 평균: (100000 + 94000 + 88002) / 3 = 94000.666... → 반올림 94001, 절단 94000
    # average() 자체는 tick 을 적용하지 않는다(plan/take_profit/stop_loss 만
    # 적용) — 그래서 이 값은 호가단위 반영 이전과 동일하다.
    assert orders.average([100000, 94000, 88002]) == 94001

    # 익절: average([1500]) = 1500(나누어떨어짐, 반올림 안 걸림) — take_profit
    # 자체의 반올림만 골라 검사한다. 1500 × 1.053 = 1579.5 → 반올림 1580
    # (파이썬 banker's rounding, 짝수인 1580 으로), 절단 1579 (구분됨).
    # 결과 1580 은 2,000원 미만이라 tick=1.
    assert orders.take_profit([1500]) == 1580

    # 손절: average([1650,1650,1650]) = 1650(나누어떨어짐) — stop_loss 자체의
    # 반올림만 골라 검사한다. 1650 × 0.91 = 1501.5 → 반올림 1502(banker's,
    # 짝수), 절단 1501 (구분됨). 결과 1502 는 2,000원 미만이라 tick=1.
    assert orders.stop_loss([1650, 1650, 1650]) == 1502


def test_아주_싼_종목에서는_부등식이_깨진다():
    """알려진 한계를 못박는다 — 고치는 게 아니라 '알고 있다'를 남긴다.

    40원 이하에서 손절선이 3차가보다 위로 올라간다(설계 §2 의 핵심 부등식이
    깨진다). 정리매매·관리종목이 아니면 닿지 않는 영역이라 막지 않기로 했다
    (plan() 독스트링 참조). 이 테스트가 실패하면 그 경계가 움직였다는 뜻이다."""
    p = orders.plan(40)
    assert orders.stop_loss([40, p["buy2"], p["buy3"]]) >= p["buy3"]
    p = orders.plan(41)
    assert orders.stop_loss([41, p["buy2"], p["buy3"]]) < p["buy3"]


def bar(t, high, low):
    """분봉 하나. 재생은 고가·저가만 본다 — 그 분 안에서 어디까지 갔는지가
    체결 판정의 전부다."""
    return {"t": t, "high": high, "low": low}



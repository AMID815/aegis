def test_같은_분에_물타기와_익절이_함께_날_수_있다():
    """분봉 하나의 고가·저가만 보므로 **분 안에서의 순서는 알 수 없다.**

    이 구현은 낙관적으로 가정한다 — 저가에서 물타기가 체결되고, 그 뒤
    가격이 고가까지 올라 내려간 익절선에 닿았다고 본다. 비관적으로 보면
    (고가 먼저, 그 뒤 하락) 익절은 안 난다.

    실제로 이 차이가 생기려면 **1분 안에 12% 넘게 출렁여야** 한다 —
    3차 체결가(-12%)보다 낮은 저가와 물타기 후 익절선(-1.0%, 호가단위
    반영 후 99,000)보다 높은 고가를 한 분봉이 동시에 가져야 하기 때문이다.
    그만큼 드물어서 낙관 가정을 그대로 둔다. 다만 승률을 아주 조금
    부풀리는 방향이라는 건 알고 있어야 한다(설계 §9 의 '순서 불명이면
    손절로' 원칙과 반대 방향).
    """
    p = orders.plan(100000)
    out = orders.replay(p, [100000], [bar("202608200900", 99000, 88000)])
    assert [o["kind"] for o in out] == ["buy2", "buy3", "take_profit"]
    assert all(o["t"] == "202608200900" for o in out)
    assert out[-1]["price"] == 99000


